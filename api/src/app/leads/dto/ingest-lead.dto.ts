import { ApiProperty, ApiPropertyOptional } from '@nestjs/swagger';
import {
  IsArray,
  IsIn,
  IsEmail,
  IsOptional,
  IsString,
  IsUrl,
} from 'class-validator';

/**
 * Payload for POST /leads/ingest.
 * Sent by the Donor Readiness Audit Lambda when an audit completes, and by other
 * services (e.g. Mirador checkout) that pass pipelineName/stageName and a note.
 */
export class IngestLeadDto {
  /** Org name extracted from the audit report (report.org_name) */
  @ApiProperty() @IsString() organization!: string;

  /** The URL that was audited (optional for non-audit sources) */
  @ApiPropertyOptional() @IsString() @IsOptional() website?: string;

  /** Presigned S3 URL for the audit PDF (generated by the Lambda, ~1 year TTL) */
  @ApiPropertyOptional() @IsString() @IsOptional() auditReportUrl?: string;

  /** Submitter email */
  @ApiPropertyOptional() @IsEmail() @IsOptional() email?: string;

  /** Submitter first name */
  @ApiPropertyOptional() @IsString() @IsOptional() firstName?: string;

  /** Submitter last name */
  @ApiPropertyOptional() @IsString() @IsOptional() lastName?: string;

  /** Submitter role / title */
  @ApiPropertyOptional() @IsString() @IsOptional() role?: string;

  /** Service interest labels derived from audit findings (already normalized) */
  @ApiPropertyOptional({ type: [String] })
  @IsArray()
  @IsString({ each: true })
  @IsOptional()
  serviceInterests?: string[];

  /** ISO date string for when the audit ran */
  @ApiPropertyOptional() @IsString() @IsOptional() auditDate?: string;

  /** Pipeline to put the card in, by name (case-insensitive). Omit for the default lead lane. */
  @ApiPropertyOptional() @IsString() @IsOptional() pipelineName?: string;

  /** Lane in that pipeline, by name (case-insensitive). Defaults to the pipeline's first lane. */
  @ApiPropertyOptional() @IsString() @IsOptional() stageName?: string;

  /** Plain-text note attached to the card. Replaces the audit "Lead Source" note when given. */
  @ApiPropertyOptional() @IsString() @IsOptional() note?: string;

  /** Title for that note. Defaults to "Details". */
  @ApiPropertyOptional() @IsString() @IsOptional() noteTitle?: string;

  /** Next action text. Defaults to the audit follow-up. */
  @ApiPropertyOptional() @IsString() @IsOptional() nextAction?: string;

  /** Where the note goes: "artifact" (Notes, the default) or "activity" (the card's Activity timeline). */
  @ApiPropertyOptional({ enum: ['artifact', 'activity'] })
  @IsIn(['artifact', 'activity'])
  @IsOptional()
  noteAs?: 'artifact' | 'activity';
}
