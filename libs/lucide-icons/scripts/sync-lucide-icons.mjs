#!/usr/bin/env node
/**
 * Regenerates the Lucide icon assets from the `lucide-static` package (pinned in the workspace
 * root package.json). Run this after bumping the `lucide-static` version to pick up new/renamed
 * icons. Nothing here runs at app build time or at runtime — it's a manual, committed-output step,
 * same spirit as `apps/api/prisma/seed.ts`.
 *
 * Writes:
 *   admin/public/lucide/lucide-sprite.svg        — served statically, fetched lazily by the app
 *   admin/public/lucide/lucide-icons-index.json  — served statically, fetched lazily by the app
 *   admin/public/lucide/lucide-version.json      — { version, iconCount, generatedAt } for reference
 *   libs/shared/src/lib/lucide-icon-names.ts     — flat name list + type, used by API validation
 *   libs/lucide-icons/src/lib/lucide-icon-paths.generated.ts — symbol inner paths for inline SVG storage
 *
 * Usage:
 *   node libs/lucide-icons/scripts/sync-lucide-icons.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, '../../..');

function resolveLucideStatic(subpath) {
  try {
    return require.resolve(`lucide-static/${subpath}`);
  } catch {
    console.error(
      'Error: lucide-static is not installed.\n' +
        'Run `npm install` from the repo root, then retry:\n' +
        '  npm run sync:lucide-icons',
    );
    process.exit(1);
  }
}

const lucidePkg = require('lucide-static/package.json');
const spriteSourcePath = resolveLucideStatic('sprite.svg');
const tagsSourcePath = resolveLucideStatic('tags.json');

const spriteSvg = readFileSync(spriteSourcePath, 'utf8');
const tags = JSON.parse(readFileSync(tagsSourcePath, 'utf8'));

// The sprite is the source of truth for "currently valid, non-deprecated" icon names — Lucide
// renames icons across versions (e.g. help-circle -> circle-help -> circle-question-mark), and the
// sprite only contains current canonical symbol ids, unlike the icons/*.svg file listing which keeps
// deprecated aliases around for backward compat.
const iconNames = [...spriteSvg.matchAll(/<symbol[^>]*\bid="([a-z0-9-]+)"/g)]
  .map((m) => m[1])
  .sort();

if (iconNames.length === 0) {
  throw new Error('No <symbol id="..."> entries found in lucide-static sprite.svg — aborting.');
}

const index = iconNames.map((name) => ({ name, tags: tags[name] ?? [] }));

/** @type {Record<string, string>} */
const iconPaths = {};
for (const match of spriteSvg.matchAll(/<symbol[^>]*\bid="([a-z0-9-]+)"[^>]*>([\s\S]*?)<\/symbol>/g)) {
  iconPaths[match[1]] = match[2].trim();
}

const adminAssetDir = resolve(repoRoot, 'admin/public/lucide');
mkdirSync(adminAssetDir, { recursive: true });

writeFileSync(resolve(adminAssetDir, 'lucide-sprite.svg'), spriteSvg);
writeFileSync(resolve(adminAssetDir, 'lucide-icons-index.json'), JSON.stringify(index));
writeFileSync(
  resolve(adminAssetDir, 'lucide-version.json'),
  JSON.stringify(
    {
      version: lucidePkg.version,
      iconCount: iconNames.length,
      generatedAt: new Date().toISOString(),
    },
    null,
    2,
  ),
);

const namesTs = `/**
 * GENERATED by libs/lucide-icons/scripts/sync-lucide-icons.mjs from lucide-static@${lucidePkg.version}.
 * Do not hand-edit. Re-run the sync script to regenerate after bumping lucide-static.
 *
 * Flat list of every valid Lucide icon name (current, non-deprecated). Used by the API to validate
 * iconKey values server-side (see api/src/app/app-config/dto/navigation-update.dto.ts) and available
 * to any consumer that needs to check a name without pulling in the browser-only lucide-icons lib.
 */
export const LUCIDE_ICON_NAMES = ${JSON.stringify(iconNames)} as const;

export type LucideIconName = (typeof LUCIDE_ICON_NAMES)[number];
`;
writeFileSync(resolve(repoRoot, 'libs/shared/src/lib/lucide-icon-names.ts'), namesTs);

const pathsTs = `/**
 * GENERATED by libs/lucide-icons/scripts/sync-lucide-icons.mjs from lucide-static@${lucidePkg.version}.
 * Do not hand-edit. Re-run the sync script to regenerate after bumping lucide-static.
 *
 * Inner SVG markup for each Lucide icon (paths/groups inside <symbol>). Used to build self-contained
 * inline SVG HTML for Quill embeds and standalone iconSvg DB columns — no sprite required at render time.
 */
export const FALLBACK_LUCIDE_ICON = 'circle-dashed';

export const LUCIDE_ICON_PATHS: Record<string, string> = ${JSON.stringify(iconPaths)};
`;
writeFileSync(
  resolve(repoRoot, 'libs/lucide-icons/src/lib/lucide-icon-paths.generated.ts'),
  pathsTs,
);

console.log(
  `Synced ${iconNames.length} icons from lucide-static@${lucidePkg.version}:\n` +
    '  admin/public/lucide/lucide-sprite.svg\n' +
    '  admin/public/lucide/lucide-icons-index.json\n' +
    '  admin/public/lucide/lucide-version.json\n' +
    '  libs/shared/src/lib/lucide-icon-names.ts\n' +
    '  libs/lucide-icons/src/lib/lucide-icon-paths.generated.ts',
);
