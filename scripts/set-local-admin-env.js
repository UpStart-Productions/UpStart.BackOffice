#!/usr/bin/env node
/**
 * Writes admin/src/environments/environment.development.generated.ts from root .env
 * so local `nx serve admin` uses Cognito when COGNITO_USER_POOL_ID + COGNITO_CLIENT_ID are set.
 */
const fs = require('fs');
const path = require('path');

require('dotenv').config({ path: path.resolve(__dirname, '../.env') });

function escape(s) {
  return (s || '').replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

const poolId = (process.env.COGNITO_USER_POOL_ID || '').trim();
const clientId = (process.env.COGNITO_CLIENT_ID || '').trim();
const region = (process.env.COGNITO_REGION || 'us-west-2').trim();
const domainPrefix = (process.env.COGNITO_DOMAIN_PREFIX || '').trim();
const customDomain = (process.env.COGNITO_CUSTOM_DOMAIN || '').trim();
const redirectSignIn = (process.env.COGNITO_REDIRECT_SIGN_IN || 'http://localhost:4201/').trim();
const redirectSignOut = (process.env.COGNITO_REDIRECT_SIGN_OUT || 'http://localhost:4201/').trim();

const useCognito = !!(poolId && clientId);

const outPath = path.join(
  __dirname,
  '..',
  'admin',
  'src',
  'environments',
  'environment.development.generated.ts',
);

let content;
if (useCognito) {
  const customDomainLine = customDomain
    ? `customDomain: '${escape(customDomain)}',`
    : 'customDomain: undefined,';
  const domainPrefixVal = domainPrefix || poolId.toLowerCase().replace(/_/g, '');
  content = `// Generated by scripts/set-local-admin-env.js - do not edit
export const environment = {
  apiBaseUrl: '/api',
  useCognito: true,
  cognitoGoogleSignIn: false,
  cognito: {
    userPoolId: '${escape(poolId)}',
    userPoolClientId: '${escape(clientId)}',
    region: '${escape(region)}',
    domainPrefix: '${escape(domainPrefixVal)}',
    ${customDomainLine}
    redirectSignIn: '${escape(redirectSignIn)}',
    redirectSignOut: '${escape(redirectSignOut)}',
  },
};
`;
} else {
  content = `// Generated by scripts/set-local-admin-env.js - do not edit
export const environment = {
  apiBaseUrl: '/api',
  useCognito: false,
  cognitoGoogleSignIn: false,
  cognito: null as {
    userPoolId: string;
    userPoolClientId: string;
    region: string;
    domainPrefix: string;
    customDomain?: string;
    redirectSignIn: string;
    redirectSignOut: string;
  } | null,
};
`;
}

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, content, 'utf8');
console.log('Wrote', outPath);
console.log('  useCognito:', useCognito);
if (useCognito) {
  console.log('  userPoolId:', poolId);
  console.log('  region:', region);
}
