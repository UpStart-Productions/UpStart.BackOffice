#!/usr/bin/env node
/**
 * Writes admin/src/environments/environment.production.generated.ts with
 * API_BASE_URL and Cognito redirect URLs from env (for Amplify builds).
 * Run before: npx nx build admin --configuration=amplify
 *
 * Env vars set in Amplify Console:
 *   API_BASE_URL            - e.g. https://api.upstartproductions.com/api
 *   AMPLIFY_REDIRECT_SIGN_IN  - e.g. https://main.xxxx.amplifyapp.com/
 *   AMPLIFY_REDIRECT_SIGN_OUT - e.g. https://main.xxxx.amplifyapp.com/
 */
const fs = require('fs');
const path = require('path');

function escape(s) {
  return (s || '').replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

const apiBaseUrl = process.env.API_BASE_URL || 'http://localhost:3001/api';
const redirectSignIn = process.env.AMPLIFY_REDIRECT_SIGN_IN || 'http://localhost:4201/';
const redirectSignOut = process.env.AMPLIFY_REDIRECT_SIGN_OUT || 'http://localhost:4201/';

const outPath = path.join(
  __dirname,
  '..',
  'admin',
  'src',
  'environments',
  'environment.production.generated.ts'
);

const content = `// Generated by scripts/set-amplify-env.js - do not edit
export const environment = {
  apiBaseUrl: '${escape(apiBaseUrl)}',
  useCognito: true,
  cognito: {
    userPoolId: 'us-west-2_lIJRXdK5X',
    userPoolClientId: '5oi5vfbt574mqect5psnqkqabn',
    region: 'us-west-2',
    domainPrefix: 'us-west-2iljrxdk5x',
    customDomain: undefined,
    redirectSignIn: '${escape(redirectSignIn)}',
    redirectSignOut: '${escape(redirectSignOut)}',
  },
};
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, content, 'utf8');
console.log('Wrote', outPath);
console.log('  apiBaseUrl:', apiBaseUrl);
console.log('  redirectSignIn:', redirectSignIn);
