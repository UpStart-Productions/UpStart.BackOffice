#!/usr/bin/env node
/**
 * Writes admin/src/environments/environment.production.generated.ts with
 * API_BASE_URL and Cognito settings from env (for Amplify builds).
 *
 * Amplify Console env vars (match Nonprofit.Mobile.Platform):
 *   API_BASE_URL, AMPLIFY_REDIRECT_SIGN_IN, AMPLIFY_REDIRECT_SIGN_OUT,
 *   AMPLIFY_COGNITO_CUSTOM_DOMAIN, AMPLIFY_MONOREPO_APP_ROOT=admin,
 *   COGNITO_USER_POOL_ID, COGNITO_CLIENT_ID, COGNITO_REGION, COGNITO_DOMAIN_PREFIX
 */
const fs = require('fs');
const path = require('path');

function escape(s) {
  return (s || '').replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function fail(message) {
  console.error(`set-amplify-env: ${message}`);
  process.exit(1);
}

function requireHttpsUrl(name, raw, { requireApiSuffix = false } = {}) {
  const url = (raw || '').trim().replace(/\/$/, '');
  if (!url) fail(`${name} is required for Amplify builds.`);

  let parsed;
  try {
    parsed = new URL(url);
  } catch {
    fail(`${name} must be a valid URL (got "${raw}").`);
  }

  const isLocalhost = parsed.hostname === 'localhost' || parsed.hostname === '127.0.0.1';
  const isIpAddress = /^\d{1,3}(\.\d{1,3}){3}$/.test(parsed.hostname);
  if (isIpAddress) {
    fail(
      `${name} must be a domain name, not an IP address (got ${parsed.hostname}). ` +
        'Use e.g. https://api.heyupstart.com/api',
    );
  }
  if (parsed.protocol !== 'https:' && !isLocalhost) {
    fail(`${name} must use HTTPS in production (got ${parsed.protocol}//${parsed.host}).`);
  }

  if (requireApiSuffix && !parsed.pathname.endsWith('/api')) {
    fail(`${name} should end with /api (got "${url}"). Example: https://api.example.com/api`);
  }

  return url;
}

const apiBaseUrl = requireHttpsUrl('API_BASE_URL', process.env.API_BASE_URL, {
  requireApiSuffix: true,
});
const redirectSignIn = requireHttpsUrl('AMPLIFY_REDIRECT_SIGN_IN', process.env.AMPLIFY_REDIRECT_SIGN_IN);
const redirectSignOut = requireHttpsUrl(
  'AMPLIFY_REDIRECT_SIGN_OUT',
  process.env.AMPLIFY_REDIRECT_SIGN_OUT,
);
const poolId = process.env.COGNITO_USER_POOL_ID || 'us-west-2_IlJRXdK5X';
const clientId = process.env.COGNITO_CLIENT_ID || '5oi5vfbt574mqect5psnqkqabn';
const region = process.env.COGNITO_REGION || 'us-west-2';
const domainPrefix = process.env.COGNITO_DOMAIN_PREFIX || 'us-west-2iljrxdk5x';
const customDomain = (
  process.env.AMPLIFY_COGNITO_CUSTOM_DOMAIN ||
  process.env.COGNITO_CUSTOM_DOMAIN ||
  ''
).trim();
const customDomainLine = customDomain
  ? `customDomain: '${escape(customDomain)}',`
  : 'customDomain: undefined,';

const outPath = path.join(
  __dirname,
  '..',
  'admin',
  'src',
  'environments',
  'environment.production.generated.ts',
);

const content = `// Generated by scripts/set-amplify-env.js - do not edit
export const environment = {
  apiBaseUrl: '${escape(apiBaseUrl)}',
  useCognito: true,
  cognitoGoogleSignIn: false,
  cognito: {
    userPoolId: '${escape(poolId)}',
    userPoolClientId: '${escape(clientId)}',
    region: '${escape(region)}',
    domainPrefix: '${escape(domainPrefix)}',
    ${customDomainLine}
    redirectSignIn: '${escape(redirectSignIn)}/',
    redirectSignOut: '${escape(redirectSignOut)}/',
  },
};
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, content, 'utf8');
console.log('Wrote', outPath);
console.log('  apiBaseUrl:', apiBaseUrl);
console.log('  redirectSignIn:', redirectSignIn);
console.log('  customDomain:', customDomain || '(none)');
